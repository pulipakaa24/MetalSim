            out["terrain"] = dict(config=self.terrain["config"], stats=self.terrain["stats"],
                                  geom=f"{UNITREE_FLOOR} (Unitree's floor plane, now type hfield)",
                                  capacity=(dict(nconmax=self.sim.d.naconmax // self.num_envs, njmax=int(self.sim.d.njmax))
                                            if self.sim is not None else "MuJoCo C (dynamic)"))
            xy = self.start_xy()
            out["starts"] = dict(rule=self.starts_kw, xy=None if xy is None else xy.round(4).tolist())
            out["pick"] = self.pick
