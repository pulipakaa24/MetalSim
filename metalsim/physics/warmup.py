"""Parallel kernel compilation at startup: build and load, on several CPU threads, the Warp modules a scene's first
step would otherwise compile one at a time on the Python thread.

Warp compiles a module lazily, when one of its kernels is first launched, so a cold start compiles the ~45 modules of a
G1 ``BatchSim`` serially (about 27 s of the 45 s cold start; research_notes/kernel_compile/PARALLEL_COMPILE.md). Two
ways to know the modules before the first step:

* :func:`preload_capture` runs the step's launch code once under ``wp.preload_launches`` inside a graph capture that
  is thrown away: every launch is recorded instead of run (MuJoCo Warp's model-specialised ``__locals__`` kernels are
  generated by that same Python code), nothing executes, and the recorded modules then compile on ``workers`` threads.
  Only for capture-safe code (``BatchSim``'s step, forward and reset already are: they are captured).
* :class:`CompileManifest` is for code that cannot run under a capture (a first step that sizes buffers from device
  results, as the MPM solver's): the modules and kernels one eager step loaded are written to a small JSON file, and
  the next run loads the ones that exist before its first step. Kernels generated during the step are not covered.

Off unless asked for: ``workers`` 0 (default) keeps Warp's lazy loading. ``METALSIM_PRELOAD_WORKERS=N`` turns it on
for every ``BatchSim`` / ``MPMCoupling`` that does not set it. The compiled output is the same as lazy loading's (the
same ``Module.load``; checked byte for byte by scripts/diagnostics/startup_compile_bench.py).
"""
from __future__ import annotations

import json
import os
import time
import warnings

import warp as wp
from warp._src.context import user_modules  # the registry of named Warp modules (no public accessor)

ENV_WORKERS = "METALSIM_PRELOAD_WORKERS"
ENV_MANIFEST_DIR = "METALSIM_COMPILE_MANIFEST_DIR"


def preload_workers(explicit: int | None = None) -> int:
    """Worker threads for startup compilation: ``explicit`` if given, else ``$METALSIM_PRELOAD_WORKERS``, else 0
    (off: Warp's lazy, serial loading)."""
    if explicit is not None:
        return max(0, int(explicit))
    try:
        return max(0, int(os.environ.get(ENV_WORKERS, "0")))
    except ValueError:
        return 0


def _available() -> bool:
    return hasattr(wp, "preload_launches")


def _stats(pl, **extra) -> dict:
    return dict(modules=pl.modules, kernels=pl.kernels, workers=pl.workers, discover_s=round(pl.discover_seconds, 4),
                load_s=round(pl.load_seconds, 4), errors=len(pl.errors), metal_compile_tasks=pl.metal_compile_tasks,
                **extra)


def preload_capture(body, device, workers: int, restore=None) -> dict | None:
    """Compile and load every kernel ``body()`` launches, on ``workers`` threads, without running anything.

    ``body`` runs once inside a ``wp.ScopedCapture`` on ``device`` whose graph is discarded, under
    ``wp.preload_launches``: launches are recorded, not recorded into the graph, and memory operations land in the
    discarded graph. ``body`` must be capture-safe and must not keep a graph it captures on its first call.
    ``restore``: an object whose attributes ``body`` may reassign (e.g. a state swap) - they are put back afterwards.
    Returns the preload statistics, or None when off (``workers`` 0, or a Warp without ``preload_launches``).
    A failure in the pass is reported and ignored: whatever it did not load compiles lazily as before."""
    if workers <= 0 or not _available():
        return None
    saved = dict(vars(restore)) if restore is not None else None
    error = None
    t0 = time.perf_counter()
    with wp.preload_launches(device, max_workers=workers) as pl:
        try:
            with wp.ScopedCapture(device=device, force_module_load=False):
                body()
        except Exception as e:  # the pass is an optimisation; the real launch reports real errors
            error = f"{type(e).__name__}: {e}"
        finally:
            if saved is not None:
                vars(restore).clear()
                vars(restore).update(saved)
    stats = _stats(pl, total_s=round(time.perf_counter() - t0, 4), error=error)
    if error is not None:
        warnings.warn(f"metalsim preload pass failed ({error}); the remaining modules compile lazily", stacklevel=2)
    return stats


def manifest_dir() -> str:
    """Where :class:`CompileManifest` files live: ``$METALSIM_COMPILE_MANIFEST_DIR``, else next to (not inside) Warp's
    versioned kernel cache, so a new Warp version or a cleared kernel cache keeps them."""
    d = os.environ.get(ENV_MANIFEST_DIR)
    if d:
        return d
    return os.path.join(os.path.dirname(os.path.normpath(wp.config.kernel_cache_dir)), "metalsim_compile_manifests")


class CompileManifest:
    """The Warp modules (and the kernels in them) one eager run of some code loaded on a device, kept in a JSON file
    named ``key``, to load them in parallel before the same code runs in a later process.

    Only modules registered under a stable name are recorded (Python modules with Warp code; ``module="unique"`` and
    generated kernels are not findable by name before they are generated). A recorded module that no longer exists
    or has different kernels is loaded as it is now, so a stale manifest costs time, never correctness."""

    def __init__(self, key: str, path: str | None = None, exclude=None):
        """``exclude``: a callable returning module names never to record or preload (evaluated when used)."""
        self.key = key
        self.path = path or os.path.join(manifest_dir(), f"{key}.json")
        self._before: set[tuple[str, int]] = set()
        self._exclude = exclude or (lambda: set())

    @staticmethod
    def _kernels(module) -> list:
        """The module's concrete kernels: plain kernels and the overloads of generic ones."""
        out = []
        for k in module._get_live_kernels():
            out.extend(k.overloads.values() if k.is_generic else [k])
        return out

    def _loaded(self, device) -> dict[tuple[str, int], list[str]]:
        """(module name, block_dim) -> keys of the kernels whose entry points were looked up (launched)."""
        out = {}
        for name, module in list(user_modules.items()):
            for (ctx, block_dim), module_exec in list(module.execs.items()):
                if ctx != device.context or module_exec is None:
                    continue
                launched = []
                for k in self._kernels(module):
                    try:
                        if module_exec.get_kernel_mangled_name(k) in module_exec.kernel_hooks:
                            launched.append(self._kernel_id(k))
                    except Exception:  # a kernel added after the load: not launched from this exec
                        pass
                out[(name, int(block_dim))] = sorted(set(launched))
        return out

    @staticmethod
    def _kernel_id(k) -> str:
        """Stable across processes: the kernel key plus, for overloads, the argument types."""
        if getattr(k, "generic_parent", None) is not None:
            return f"{k.key}:{k.sig}"
        return str(k.key)

    def mark(self, device) -> None:
        """Remember what is loaded now, so that :meth:`record` keeps only what the code after this loads."""
        self._before = set(self._loaded(wp.get_device(device)))

    def record(self, device) -> None:
        """Write the modules loaded on ``device`` since :meth:`mark` (all of them without a mark)."""
        loaded = self._loaded(wp.get_device(device))
        excluded = self._exclude()
        entries = [{"module": n, "block_dim": b, "kernels": k} for (n, b), k in sorted(loaded.items())
                   if (n, b) not in self._before and n not in excluded]
        os.makedirs(os.path.dirname(self.path), exist_ok=True)
        tmp = f"{self.path}.{os.getpid()}.tmp"
        with open(tmp, "w") as f:
            json.dump({"key": self.key, "warp": wp.config.version, "entries": entries}, f, indent=1)
        os.replace(tmp, self.path)

    def preload(self, device, workers: int) -> dict | None:
        """Load the recorded modules that exist now, on ``workers`` threads, before the code runs."""
        if workers <= 0 or not _available() or not os.path.exists(self.path):
            return None
        device = wp.get_device(device)
        try:
            with open(self.path) as f:
                entries = json.load(f)["entries"]
        except (OSError, ValueError, KeyError):
            return None
        t0 = time.perf_counter()
        missing = 0
        excluded = self._exclude()
        with wp.preload_launches(device, max_workers=workers) as pl:
            for e in entries:
                if e["module"] in excluded:
                    continue
                module = user_modules.get(e["module"])
                if module is None:
                    missing += 1
                    continue
                wanted = set(e["kernels"])
                kernels = self._kernels(module)
                hits = [k for k in kernels if self._kernel_id(k) in wanted] or kernels[:1]
                for k in hits:      # one kernel is enough to load the module; the listed ones also get pipelines
                    pl.add(k, device, e["block_dim"])
        return _stats(pl, total_s=round(time.perf_counter() - t0, 4), manifest_missing=missing,
                      manifest_entries=len(entries))
