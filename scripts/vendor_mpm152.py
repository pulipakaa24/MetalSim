#!/usr/bin/env python3
"""Regenerate ``metalsim/physics/mpm/implicit_mpm`` from the pinned Newton fork commit.

MetalSim's main simulator (``.venv``: MuJoCo 3.14, MuJoCo Warp fork, Newton 1.7 line) runs Isaac Lab 3.0-EA's MPM
solver, Newton 1.5.2's ``SolverImplicitMPM`` with MetalSim's Metal changes (pulipakaa24/newton ``metalsim-1.5.2``),
as a vendored copy: the package's files unchanged except for the six relative imports that reach outside the
package (``from ...core.types import override`` and so on), which become absolute ``newton._src`` imports, so the
copy runs against whichever Newton the environment has (1.7 in ``.venv``, 1.5.2 in ``.venv-newton152``). Kernels are
byte-for-byte the fork's, so results are the fork's wherever the inputs are (``tests/test_mpm_main.py``).

Usage:
    python scripts/vendor_mpm152.py [NEWTON_CHECKOUT]     # default: download the pinned commit's tarball
    python scripts/vendor_mpm152.py --check [NEWTON_CHECKOUT]   # exit 1 if the vendored copy differs

The pin below must equal ``scripts/setup_newton152.sh``'s ``PIN`` (checked by ``tests/test_mpm_main.py``).
"""
from __future__ import annotations

import argparse
import hashlib
import io
import pathlib
import re
import sys
import tarfile
import tempfile
import urllib.request

PIN = "3fd1f052a5ad031578960d9642aaaedc03834e4d"
REPO = "https://github.com/pulipakaa24/newton"
SRC_DIR = "newton/_src/solvers/implicit_mpm"
ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / "metalsim" / "physics" / "mpm" / "implicit_mpm"
HEADER = (
    "# Vendored by MetalSim from pulipakaa24/newton @ {pin} ({path}); generated by scripts/vendor_mpm152.py.\n"
    "# Do not edit: change the fork, re-pin, and regenerate. Only the imports that leave the package are rewritten.\n"
)


def rewrite(text: str) -> str:
    """The only change to a source file: package-external relative imports become absolute ``newton._src`` ones."""
    text = re.sub(r"^(\s*)from \.\.\.([A-Za-z_][\w.]*) import", r"\1from newton._src.\2 import", text, flags=re.M)
    text = re.sub(r"^(\s*)from \.\.([A-Za-z_][\w.]*) import", r"\1from newton._src.solvers.\2 import", text, flags=re.M)
    return text


def sources(checkout: pathlib.Path | None) -> dict[str, bytes]:
    if checkout is not None:
        d = checkout / SRC_DIR
        return {p.name: p.read_bytes() for p in sorted(d.glob("*.py"))}
    url = f"{REPO}/archive/{PIN}.tar.gz"
    with urllib.request.urlopen(url) as r:  # noqa: S310 (pinned GitHub archive)
        data = r.read()
    out = {}
    with tarfile.open(fileobj=io.BytesIO(data)) as tf:
        for m in tf.getmembers():
            parts = m.name.split("/", 1)
            if len(parts) == 2 and parts[1].startswith(SRC_DIR + "/") and m.name.endswith(".py") and m.isfile():
                name = parts[1][len(SRC_DIR) + 1:]
                if "/" not in name:
                    out[name] = tf.extractfile(m).read()
    return dict(sorted(out.items()))


def generate(src: dict[str, bytes]) -> dict[str, str]:
    files = {}
    for name, raw in src.items():
        text = raw.decode()
        files[name] = HEADER.format(pin=PIN, path=f"{SRC_DIR}/{name}") + rewrite(text)
    manifest = [f"pulipakaa24/newton {PIN} {SRC_DIR}", ""]
    manifest += [f"{hashlib.sha256(raw).hexdigest()}  {name}" for name, raw in src.items()]
    files["SOURCE.txt"] = "\n".join(manifest) + "\n"
    return files


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("checkout", nargs="?", type=pathlib.Path)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dest", type=pathlib.Path, default=DEST)
    a = ap.parse_args()
    files = generate(sources(a.checkout))
    if a.check:
        bad = [n for n, t in files.items() if not (a.dest / n).exists() or (a.dest / n).read_text() != t]
        extra = sorted({p.name for p in a.dest.glob("*.py")} - set(files))
        if bad or extra:
            print("vendored implicit_mpm differs from the pin:", bad, "extra:", extra)
            return 1
        print(f"vendored implicit_mpm equals pulipakaa24/newton@{PIN[:8]} ({len(files) - 1} files)")
        return 0
    a.dest.mkdir(parents=True, exist_ok=True)
    for p in a.dest.glob("*.py"):
        p.unlink()
    for n, t in files.items():
        (a.dest / n).write_text(t)
    print(f"wrote {len(files)} files to {a.dest}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
