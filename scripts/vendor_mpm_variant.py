#!/usr/bin/env python3
"""Generate MetalSim's flag-gated implicit-MPM variants from the vendored 1.5.2 copy.

``metalsim/physics/mpm/implicit_mpm`` is the byte-identical copy of the Newton 1.5.2 fork's solver (Isaac Lab's;
``scripts/vendor_mpm152.py``) and is never edited. A *variant* is a second package beside it: the vendored files
plus an upstream Newton change applied as a patch, selected with ``MPMConfig(solver_variant=...)`` (default
``"parity"``: the vendored copy, so the Isaac-parity path is untouched; research_notes/sand_fidelity/PLAN_2026-10-14.md
section 9, prerequisite P1).

Variants:

* ``pr4660`` -> ``metalsim/physics/mpm/implicit_mpm_pr4660``: Newton draft PR #4660 ("Improve implicit MPM strain
  and collider robustness", head 1de47831): P1d / Q1d nodal mass diagonalisation with null modes dropped, Q1d on
  Gauss-Legendre nodes, sign-consistent material moments, angle-weighted collider pseudonormals with a fallback when
  they cancel, viscosity only on strain nodes with volume. Patch: ``patches/newton/pr4660-1de47831-implicit-mpm.diff``
  (the PR's four solver files; its base is Newton main, and every hunk applies to the 1.5.2 copy).

    python scripts/vendor_mpm_variant.py            # regenerate every variant (needs the ``patch`` tool)
    python scripts/vendor_mpm_variant.py --check    # exit 1 if a committed variant differs from a fresh generation

Each generated .py keeps Newton's SPDX lines and replaces the vendored copy's modification notice by the variant's.
``tests/test_mpm_variant.py`` regenerates and compares.
"""
from __future__ import annotations

import argparse
import pathlib
import shutil
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parents[1]
VENDORED = ROOT / "metalsim/physics/mpm/implicit_mpm"
VARIANTS = {
    "pr4660": {
        "dest": ROOT / "metalsim/physics/mpm/implicit_mpm_pr4660",
        "patch": ROOT / "patches/newton/pr4660-1de47831-implicit-mpm.diff",
        "source": "Newton draft PR #4660 (https://github.com/newton-physics/newton/pull/4660) at 1de47831",
    },
}


def _notice(name: str, file: str, spec: dict) -> list[str]:
    return [f"# Modified by MetalSim (Apache-2.0 section 4): MetalSim's vendored 1.5.2 copy of this file "
            f"(metalsim/physics/mpm/implicit_mpm/{file})",
            f"# with {spec['source']} applied, by scripts/vendor_mpm_variant.py (variant {name!r}, selected with",
            "# MPMConfig(solver_variant=...)). Do not edit: change the patch and regenerate."]


def _renotice(text: str, name: str, file: str, spec: dict) -> str:
    lines = text.split("\n")
    i = next(k for k, ln in enumerate(lines) if ln.startswith("# Modified by MetalSim"))
    j = i
    while j < len(lines) and lines[j].startswith("#"):
        j += 1
    return "\n".join(lines[:i] + _notice(name, file, spec) + lines[j:])


def generate(name: str) -> dict[str, str]:
    """{file name: text} of variant ``name`` (the vendored package's files, patched, re-noticed, plus NOTICE.txt)."""
    spec = VARIANTS[name]
    if shutil.which("patch") is None:
        raise RuntimeError("the 'patch' tool is required to generate solver variants")
    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        for p in VENDORED.glob("*.py"):
            shutil.copy2(p, work / p.name)
        r = subprocess.run(["patch", "-p1", "-s", "--no-backup-if-mismatch", "-F", "0", "-i", str(spec["patch"])],
                           cwd=work, capture_output=True, text=True)
        if r.returncode != 0 or list(work.glob("*.rej")):
            raise RuntimeError(f"variant {name}: the patch does not apply cleanly:\n{r.stdout}{r.stderr}")
        files = {p.name: _renotice(p.read_text(), name, p.name, spec) for p in sorted(work.glob("*.py"))}
    files["NOTICE.txt"] = (
        f"MetalSim implicit-MPM solver variant {name!r}\n\n"
        f"The files of metalsim/physics/mpm/implicit_mpm (MetalSim's vendored copy of the Newton 1.5.2 fork's\n"
        f"solver; see its NOTICE.txt) with {spec['source']} applied:\n"
        f"{spec['patch'].relative_to(ROOT)}. Copyright (c) 2025-2026 The Newton Developers. Licensed under the\n"
        f"Apache License, Version 2.0 (licenses/Apache-2.0.txt in this repository). This directory is offered under\n"
        f"the Apache License 2.0, not under MetalSim's MIT licence.\n\n"
        f"Modifications (Apache-2.0 section 4(b)): generated by scripts/vendor_mpm_variant.py, which copies the\n"
        f"vendored files, applies the patch without fuzz, and replaces each file's modification notice. Selected\n"
        f"only with MPMConfig(solver_variant={name!r}); the default ('parity') runs the vendored copy.\n")
    return files


def write(name: str) -> None:
    dest = VARIANTS[name]["dest"]
    files = generate(name)
    dest.mkdir(parents=True, exist_ok=True)
    for p in dest.iterdir():
        if p.is_file() and p.name not in files:
            p.unlink()
    for fname, text in files.items():
        (dest / fname).write_text(text)
    print(f"{name}: wrote {len(files)} files to {dest.relative_to(ROOT)}")


def check(name: str) -> list[str]:
    dest = VARIANTS[name]["dest"]
    files = generate(name)
    bad = [f for f, t in files.items() if not (dest / f).exists() or (dest / f).read_text() != t]
    extra = [p.name for p in dest.iterdir() if p.is_file() and p.name not in files] if dest.exists() else []
    return bad + extra


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        bad = {n: check(n) for n in VARIANTS}
        for n, b in bad.items():
            print(f"{n}: {'up to date' if not b else 'differs: ' + ', '.join(b)}")
        return 1 if any(bad.values()) else 0
    for n in VARIANTS:
        write(n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
