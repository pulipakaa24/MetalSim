"""Move MetalSim's Warp and Newton (metalsim-1.5.2) pins (batch_08).
    python3 pin_bump.py REPO OLD_WARP NEW_WARP OLD_NEWTON NEW_NEWTON      (full 40-hex SHAs)
Warp: every occurrence in scripts/setup_warp.sh; elsewhere only on lines that state the current pin (README "pinned by",
GUIDE "pinned commit" / the fallback diff, MPM.md section 10 rows); historical mentions stay. Newton: every occurrence
outside runs/, patches/ and CHANGELOG.md (the old pin is the current one everywhere it appears). Prints each edit."""
import pathlib
import subprocess
import sys

repo, ow, nw, on, nn = sys.argv[1:6]
R = pathlib.Path(repo)
WARP_MARKERS = ("pinned by", "pinned commit", "patches/warp/metalsim-", "shared Warp fork @", "pinned `")


def sub_line(path, old_full, new_full, markers=None):
    p = R / path
    if not p.exists():
        return
    lines = p.read_text().split("\n")
    changed = 0
    for i, line in enumerate(lines):
        if old_full[:8] not in line:
            continue
        if markers is not None and not any(m in line for m in markers):
            continue
        new = line.replace(old_full, new_full).replace(old_full[:8], new_full[:8])
        if new != line:
            lines[i] = new
            changed += 1
    if changed:
        p.write_text("\n".join(lines))
        print(f"{path}: {changed} line(s)")


sub_line("scripts/setup_warp.sh", ow, nw)
for f in ("README.md", "docs/GUIDE.md", "metalsim/physics/mpm/MPM.md"):
    sub_line(f, ow, nw, WARP_MARKERS)

files = subprocess.run(["git", "-C", repo, "grep", "-l", on[:8]], capture_output=True, text=True).stdout.split()
for f in files:
    if f.startswith(("runs/", "patches/")) or f == "CHANGELOG.md" or f.startswith("metalsim/physics/mpm/implicit_mpm/"):
        continue  # the vendored package is regenerated by scripts/vendor_mpm152.py
    sub_line(f, on, nn)
left = subprocess.run(["git", "-C", repo, "grep", "-n", on[:8], "--", "scripts", "README.md", "docs/GUIDE.md"],
                      capture_output=True, text=True).stdout
print("old Newton pin still mentioned in scripts/README/GUIDE:" if left else "old Newton pin gone from scripts/README/GUIDE")
print(left)
